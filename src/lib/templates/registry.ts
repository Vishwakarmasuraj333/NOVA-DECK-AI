/**
 * Fast lookup helper for templates by slug or ID.
 */
export function getTemplateById(idOrSlug: string): TemplateDefinition | undefined {
  if (!idOrSlug) return TEMPLATES[0];
  return TEMPLATES.find(
    (t) =>
      t.id.toLowerCase() === idOrSlug.toLowerCase() ||
      t.slug.toLowerCase() === idOrSlug.toLowerCase()
  );
}

/**
 * Returns list of distinct categories.
 */
export function getAllCategories(): string[] {
  const cats = new Set<string>();
  cats.add("All");
  TEMPLATES.forEach((t) => cats.add(t.category));
  return Array.from(cats);
}

/**
 * Returns filtered templates by category.
 */
export function getTemplatesByCategory(category: string): TemplateDefinition[] {
  if (!category || category === "All") return TEMPLATES;
  return TEMPLATES.filter((t) => t.category.toLowerCase() === category.toLowerCase());
}

/**
 * Returns free templates.
 */
export function getFreeTemplates(): TemplateDefinition[] {
  return TEMPLATES.filter((t) => !t.isPremium);
}

/**
 * Returns premium templates.
 */
export function getPremiumTemplates(): TemplateDefinition[] {
  return TEMPLATES.filter((t) => t.isPremium);
}

/**
 * Search templates by query string.
 */
export function searchTemplates(query: string): TemplateDefinition[] {
  if (!query || !query.trim()) return TEMPLATES;
  const q = query.toLowerCase().trim();
  return TEMPLATES.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      t.tags.some((tag) => tag.toLowerCase().includes(q))
  );
}
