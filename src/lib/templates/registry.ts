export function getTemplateById(idOrSlug: string): TemplateDefinition | undefined {
  return TEMPLATES.find((t) => t.id === idOrSlug || t.slug === idOrSlug) || TEMPLATES[0];
}

export function getAllCategories(): string[] {
  const categories = new Set(TEMPLATES.map((t) => t.category));
  return ["All", ...Array.from(categories)];
}
